#!/usr/bin/env python3
"""Build web/promo/player.html: one self-contained page that runs every promo scene (player.html?scene=<id>).

Why one built file: browsers refuse ES modules from file://, so the page inlines core + cast + all scenes into a single
<script type="module"> and opens with a double-click. Each scene sits in its own scope (no name clashes).
No copied styles: the dashboard's and the red team console's CSS are read from web/index.html and web/redteam.html at
build time, and the player inserts only the one the scene needs (they clash when loaded together).

Edit src/*.js or ui/promo.css, then run:   python3 web/promo/build.py
Three.js still comes from the CDN (importmap), so the first open needs the internet."""
import re, json, pathlib
HERE = pathlib.Path(__file__).resolve().parent
SRC, WEB = HERE / 'src', HERE.parent

# scene id → (module, call, component css, <html data-stage>)
SCENES = {
    'bothive-launch': ('bothive', "run('launch')", 'redteam', ''),
    'feed': ('story', "run('feed')", 'radar', ''),
    'market': ('market', 'run()', 'radar', ''),
    'shop': ('shop', 'run()', 'radar', ''),
    'social': ('social', 'run()', 'radar', ''),
    'decay': ('story', "run('decay')", 'radar', 'home'),
    'intercept': ('intercept', 'run()', 'radar', 'result'),
    'bothive-caught': ('bothive', "run('caught')", 'redteam', ''),
    'outro': ('outro', 'run()', 'radar', 'home'),
}
THREE_IMPORT = re.compile(r"^import\s[^;]*?from\s+'three[^']*';\s*$", re.M | re.S)
LOCAL_IMPORT = re.compile(r"^import\s[^;]*?from\s+'\./[^']+';\s*$", re.M | re.S)

def strip(js):
    js = LOCAL_IMPORT.sub('', js)
    js = re.sub(r'^export\s+\{[^}]*\};\s*$', '', js, flags=re.M)
    return re.sub(r'^export\s+(?=(const|let|function|class)\b)', '', js, flags=re.M)

def page_css(name):  # the <style> of the real page: the components are reused, not copied
    html = (WEB / f'{name}.html').read_text()
    return re.search(r'<style>\n?(.*?)</style>', html, re.S).group(1)

core = (SRC / 'core.js').read_text()
imports = '\n'.join(THREE_IMPORT.findall(core))
modules = sorted({m for m, *_ in SCENES.values()})
scoped = '\n'.join(f"const M_{m} = (() => {{\n{strip((SRC / f'{m}.js').read_text())}\nreturn {{run}};\n}})();" for m in modules)
runners = ',\n  '.join(f"'{sid}': () => M_{m}.{call}" for sid, (m, call, _, _) in SCENES.items())
setup = json.dumps({sid: {'css': css, 'stage': stage} for sid, (_, _, css, stage) in SCENES.items()})
css = json.dumps({n: page_css(n) for n in ('index', 'redteam')}).replace('</', '<\\/')

js = f"""{imports}
// ---- core.js
{strip(THREE_IMPORT.sub('', core))}
// ---- cast.js
{strip((SRC / 'cast.js').read_text())}
// ---- scenes, each in its own scope
{scoped}
// ---- the player: the component styles this scene needs (taken from web/index.html or web/redteam.html), then the scene
const PAGE_CSS = {css};
const SETUP = {setup};
const RUN = {{
  {runners}
}};
const sc = SETUP[SCENE_ID] ? SCENE_ID : SCENES[0].id;
const st = document.createElement('style'); st.textContent = PAGE_CSS[SETUP[sc].css === 'radar' ? 'index' : 'redteam'];
document.head.prepend(st);
if (SETUP[sc].stage) document.documentElement.dataset.stage = SETUP[sc].stage;
document.title = `Promo · ${{SCENES.find(s => s.id === sc).name}}`;
RUN[sc]();
""".replace('</script', '<\\/script')

(HERE / 'player.html').write_text(f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Promo</title>
<link rel="icon" href="data:,">
<link rel="stylesheet" href="ui/promo.css">
<script type="importmap">
{{"imports":{{
  "three":"https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.module.js",
  "three/addons/":"https://cdn.jsdelivr.net/npm/three@0.160.0/examples/jsm/"
}}}}
</script>
</head>
<body>
<!-- generated by build.py from src/ — edit src/*.js and rebuild -->
<script type="module">
{js}
</script>
</body>
</html>
''')
print('built player.html with scenes:', ', '.join(SCENES))
